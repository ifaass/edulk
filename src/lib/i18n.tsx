export type MsgKey = keyof typeof messages.en;

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MsgKey) => string;
};

const Ctx = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("si");

  useEffect(() => {
    const saved = localStorage.getItem(KEY);
    if (saved === "en" || saved === "si" || saved === "ta") setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "en" ? "en" : lang;
  }, [lang]);

  const setLang = (next: Lang) => {
    setLangState(next);
    localStorage.setItem(KEY, next);
  };

  const t = (key: MsgKey) => messages[lang][key] || messages.en[key];

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(Ctx);
  if (!value) throw new Error("i18n");
  return value;
}
